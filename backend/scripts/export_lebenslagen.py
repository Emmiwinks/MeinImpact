#!/usr/bin/env python3
"""Writes the Lebenslagen catalog as Dart for the app.

`ai/lebenslagen.py` is the single source; the app gets a generated, const
copy so the picker works offline and without asset loading. Run after every
catalog change (plain Python, no dependencies, so it also runs on the host),
then format the output:
  python backend/scripts/export_lebenslagen.py
  cd app && dart format lib/src/features/feed/domain/lebenslagen_catalog.g.dart
"""

import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO / "backend" / "src"))

from meinimpact.infrastructure.ai.lebenslagen import AREAS, LEBENSLAGEN  # noqa: E402

_TARGET = (
    _REPO
    / "app"
    / "lib"
    / "src"
    / "features"
    / "feed"
    / "domain"
    / "lebenslagen_catalog.g.dart"
)


def _dart(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return f"'{escaped}'"


def render() -> str:
    lines = [
        "// GENERATED by backend/scripts/export_lebenslagen.py from",
        "// backend/src/meinimpact/infrastructure/ai/lebenslagen.py. Do not edit.",
        "",
        "import 'lebenslage.dart';",
        "",
        "const kLebenslageAreas = <String>[",
        *(f"  {_dart(area)}," for area in AREAS),
        "];",
        "",
        "const kLebenslagen = <Lebenslage>[",
    ]
    for item in LEBENSLAGEN:
        # Trailing comma so `dart format` puts long lists one per line.
        synonyms = "".join(f"{_dart(s)}, " for s in item.synonyms).rstrip()
        lines += [
            "  Lebenslage(",
            f"    id: {_dart(item.id)},",
            f"    label: {_dart(item.label)},",
            f"    area: {_dart(item.area)},",
            *(["    isPrivate: true,"] if item.private else []),
            f"    synonyms: [{synonyms}],",
            "  ),",
        ]
    lines += ["];", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    _TARGET.write_text(render(), encoding="utf-8")
    print(f"{len(LEBENSLAGEN)} Lebenslagen -> {_TARGET}")
